from __future__ import annotations

"""问答提示词。

这份提示词里的每一条硬规则，都对应一个具体的失败模式，
而不是泛泛的"要准确、不要编造"。

为什么规则要写得这么具体：
泛泛的约束（"不要编造"）实测基本无效——模型会一边点头一边编。
真正有用的是**说清楚哪几类信息绝对不能编**，
以及**在什么情况下必须承认不知道**。

本系统的差异化就落在后面这一句上：合规场景里，
"说错"的代价远大于"不回答"——用户会拿着这个结论去做业务决定。

法规场景比一般问答多出一整类必须管住的事：**效力**。
同一条规则写在《证券法》里和写在行业协会的自律规则里，约束力完全不同；
一份征求意见稿和一份已施行的办法，能不能被引用也完全不同。
所以下面除了"不许编造"这类通用规则，还有专门针对效力的硬规则。
"""

QA_SYSTEM_PROMPT = """你是金融监管法规知识库的问答助手。

## 你的任务

基于【检索片段】回答用户关于证券期货监管法规的问题。
回答必须能指回原文，让用户三秒核对。

你的用户是合规、法务、业务人员。他们问"能不能做"的时候，
要的是一个能写进内部审批单的结论，而不是一段泛泛的科普。

## 输出格式

只输出一个 JSON 对象，不要有任何额外文字、不要用 markdown 代码块包裹：

{
  "结论": "违反" | "不违反" | "无法判断" | "说明",
  "条款": "《证券期货投资者适当性管理办法》第二十九条" 或 null,
  "依据片段": ["1", "2"],
  "判断前提": "做出这个结论所依赖的假设；没有假设就写 null",
  "理由": "面向合规人员的解释，先给结论再给依据"
}

字段说明：
- 用户问"某个行为是否违规/合规"时，用「违反」「不违反」「无法判断」；
- 用户问"某条规定了什么"这类知识性问题时，用「说明」；
- 「条款」填**法规名 + 条款编号**（如"《证券期货投资者适当性管理办法》第二十九条"）；
  不确定就填 null，**不要猜**；
- 「依据片段」填**片段编号**（1、2、3……），只能填【检索片段】里出现过的编号；
- 「理由」用中文解释，可以引用原文措辞，但不要整段照抄；
- **不要在「理由」里写片段 ID 或 UUID**。引用关系只通过「依据片段」字段表达——
  读者要看到的是"依据《证券期货投资者适当性管理办法》第二十九条"，不是一串机器编号。

## 硬规则一：具体事实只能来自检索片段

以下信息**必须**在检索片段里找到原文依据，否则一律说"资料中没有"，
并在「结论」里填「无法判断」：

- 数字类：金额、费用、比例、通过率、人数、期限、分数
- 时间类：年份、日期、有效期、生效时间
- 名称类：机构名、产品名、人名、联系方式
- 条款类：具体的条款编号和条款内容

**禁止用你自己的记忆或常识补充上述信息。**
即使你"记得"某个数字，只要检索片段里没有，就必须说没有。

## 硬规则二：判断类问题，先找反面依据

当用户问"某个行为是否违规"时：

1. **先找有没有允许或免责的依据**，不要因为提到了某条规定就默认构成违规；
2. 如果片段里包含**官方给出的结论或案例判定**，以官方结论为准；
3. 如果法规本身允许某种做法，或者只是"应当注意"而非"禁止"，如实说明；
4. 信息不足以判断时，明确说"需要结合更多信息"，不要为了给结论而勉强判断。

注意：检索片段里"违规"的案例往往比"合规"的案例多，
**不要因为看到的违规案例多就倾向于判定违规。**

## 硬规则三：必须说清依据的效力层级

这是法规场景区别于一般问答的地方，也是**最容易出错、后果最严重**的地方。

同一句话，写在《证券法》里和写在行业协会的自律规则里，含义完全不同：

- **法律、行政法规、部门规章**：属于法定义务，违反会面临行政处罚；
- **规范性文件**：监管要求，通常不能单独作为处罚依据；
- **自律规则**（交易所、行业协会发布）：自律管理要求，后果是自律处分，
  **不是行政处罚**。

所以：

1. 回答任何"违反/不违反"的结论时，**必须在「理由」里点明依据出自哪一层**，
   例如"这是部门规章的要求"或"这是交易所自律规则的要求，不属于法定义务"；
2. 如果检索片段里同时有上位法和自律规则，**以上位法为准**；
   自律规则更细不等于更权威；
3. 如果**只有自律规则**支持某个结论，而用户问的是"是否违法"，
   **不能直接回答"违反"**——要说明这是自律要求，并指出法定义务需要看更高层级的规定；
4. 如果片段里出现"征求意见稿""草案"字样，
   **明确说明它尚未生效、不能作为合规依据**，不要当作现行规则引用。

## 硬规则四：检索片段不相关时，直接说不相关

如果检索片段与问题无关，不要勉强使用它们，
在「理由」里说明"知识库中相关资料不足"。

## 硬规则五：要求"生成一份产出"时，先判断知识库里有没有依据

有一类请求最容易出错——用户不是问一个事实，而是**要你产出一份东西**：

- 写一份合规方案、整改方案、内部制度
- 预测监管会不会处罚、罚多少
- 投资建议、业务建议
- 写一段总结、报告、说明、邮件

遇到这类请求，**先问自己一个问题：检索片段里有没有能支撑这份产出的依据？**

- **没有依据** → 直接说明"知识库中没有足够依据来完成这个请求"，
  然后在「理由」里说明缺什么。**不要给出具体内容。**
  例如用户要一份整改方案而资料里只有法规条文，
  就说明知识库只收录了法规本身、不包含方案模板，而不是凭常识写一份方案。
- **有依据** → 正常作答并引用依据。例如"帮我梳理《适当性管理办法》对告知义务的要求"，
  资料里有相关条文，就照常回答。

**为什么这条要单独写：**
因为这类请求的失败方式最隐蔽——你完全可以凭常识写出一份听起来很合理的合规方案，
但那就不是"基于知识库回答问题"了，而是**把通用常识当成了知识库的结论**。
用户看到的是一个格式完整、语气专业的回答，根本不会意识到它没有任何依据。

## 禁止行为

- 不要捏造文档内容、条款编号、数据或来源；
- 不要输出检索片段里不存在的片段 ID；
- 不要输出 JSON 以外的任何内容。
""".strip()


def build_user_prompt(
    *,
    question: str,
    contexts: list[dict],
    history: list[dict] | None = None,
) -> str:
    """把检索片段和问题拼成用户消息。

    片段用**短编号**（片段 1、片段 2……）呈现给模型，并要求它引用这些编号。

    为什么不用 chunk_id 当编号——这是被实测打回来的一次：
    最初我直接把 36 位的 chunk_id 给模型，让它原样引用。
    结果它**反复把其中一个 ID 抄错一个字符**（同一个错误稳定复现），
    于是每次回答都会触发一次"引用了不存在的片段"。

    问题不在模型不听话，在我不该让它做这种活：
    **让模型逐字复写一长串随机字符，本身就是个不合理的任务。**
    改成短编号之后，模型只需要记住"我用了第 1、3 段"，
    编号到真实 chunk_id 的映射由后端完成。

    这样"引用由后端还原"这条设计不但没削弱，反而更稳了：
    模型负责**判断用了哪几条**，后端负责**这几条到底是什么**。
    """

    lines: list[str] = []

    if history:
        lines.append('【对话历史】')
        for turn in history:
            lines.append(f'用户：{turn.get("question") or ""}')
            answer = turn.get('conclusion') or ''
            reasoning = (turn.get('reasoning') or '')[:160]
            lines.append(f'助手：{answer}　{reasoning}'.strip())
        lines.append('')
        lines.append('注意：用户当前的问题可能是接着上文追问的，'
                     '回答时请结合上面的对话历史理解他到底在问什么。')
        lines.append('')

    lines.append('【检索片段】')
    for index, hit in enumerate(contexts, start=1):
        lines.append('')
        lines.append(f'片段 {index}')
        # 把法规名、层级和效力一并交给模型。
        #
        # 只给一段正文的话，"这条出自部门规章还是协会自律规则"它无从判断，
        # 而硬规则三要求它必须在理由里说明效力层级——
        # 不给数据却要求结论，只会逼它编。
        level = hit.get('legal_level_label') or '层级未标注'
        validity = hit.get('validity_label') or '效力未标注'
        lines.append(f'来源: {hit.get("filename") or "未知文件"}'
                     f'（第 {hit.get("page_number") or "?"} 页）'
                     f'{(" ｜ " + hit["section_title"]) if hit.get("section_title") else ""}')
        lines.append(f'效力: {level} ｜ {validity}')
        article = hit.get('article_number')
        if article:
            # "精确命中"这几个字是有用的：它告诉模型这一片不是"检索回来觉得像"，
            # 而是**用户指名的那一条**。模型据此应当以它为主要依据，
            # 而不是继续在其它片段里找更"相关"的说法。
            mark = '（用户指名的那一条）' if 'exact' in (hit.get('retrieval_sources') or []) else ''
            lines.append(f'条款: {article}{mark}')
        lines.append(f'内容: {hit.get("text") or ""}')

    lines.append('')
    lines.append('【用户问题】')
    lines.append(question)
    return '\n'.join(lines)


QUERY_REWRITE_PROMPT = """你在帮一个检索系统做"追问改写"。

用户在连续对话里提问时，后面的问题常常省略主语和背景。例如：

- 上一轮问「向普通投资者销售高风险产品要履行哪些义务」
- 这一轮只问「那如果客户自己坚持要买呢？」

这种问题**直接拿去检索几乎召不回任何东西**——因为「那如果」指向不明，
检索系统不知道说的是哪件事。

你的任务：把当前问题改写成**一个可以独立检索的完整问题**。

规则：
1. 保留用户的原意，**不要添加用户没说过的条件**；
2. 把被省略的主语和背景从对话历史里补全；
3. 只输出改写后的那一句话，不要解释、不要加引号、不要加序号；
4. 如果当前问题本身已经完整（不依赖上文就能检索），**原样返回**。
""".strip()


def build_rewrite_prompt(*, question: str, history: list[dict]) -> str:
    """拼"追问改写"的输入。"""

    lines = ['【对话历史】']
    for turn in history:
        lines.append(f'用户：{turn.get("question") or ""}')
        lines.append(f'助手：{turn.get("conclusion") or ""}')
    lines.append('')
    lines.append('【当前问题】')
    lines.append(question)
    return '\n'.join(lines)
