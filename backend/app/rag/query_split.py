from __future__ import annotations

import re

"""查询拆分：把"对比类"问题拆成几条子查询，各自去召回。

解决的是一个**排序解决不了的问题**：

基线里"跨业务线差异"这个维度只有 33%，而且调文档多样性几乎没改善（33% → 33%）。
原因是根本性的——**那些题的第二个业务线，压根不在候选池里。**

    问："证券和期货在适当性义务上的法律规定有什么区别"
    候选里全是从《证券法》《证券公司监督管理条例》里召回的切片，
    《期货和衍生品法》第五十条一条都没进来。

重排只能对**已经召回的**候选重新排序。候选里没有的东西，排序再怎么调也变不出来。

所以要在**检索之前**动手：把问题按业务线拆开，让每条业务线各自去召回自己的依据，
再把两边的候选并到一起。这样《期货和衍生品法》才有机会进入候选池。

为什么用规则而不是让大模型改写：

  1. **业务线是个封闭集合**（证券 / 期货 / 基金），命不命中一目了然，
     不需要语义理解；
  2. 规则是确定的、可测的、不花钱的。为一个人家已经写清楚的结构调一次模型，
     换来的是延迟和不确定性；
  3. **拆分错了代价可控**：拆出来的子查询只是往候选池里"多加几条"，
     主查询本身仍然照常检索。所以这是一个只增不减的动作，不是一个会翻车的动作。

⚠️ 子查询的构造方式，这一步比想象中要紧——踩过一次：

第一版是"业务线名 + 原问题"，也就是

    "证券 证券和期货在适当性义务上的法律规定有什么区别"
    "期货 证券和期货在适当性义务上的法律规定有什么区别"

看起来只是加了个前缀，但那两条子查询**里面仍然有对方的名字**，
问的其实是同一件事。实测结果：两条子查询各自选出的"最像的一片"
是**同一片**——《问答》里那段泛泛而谈的概述，因为它同时匹配"证券"和"期货"。

于是"每条业务线保底一个位置"形式上做到了（两条都进了结果），
实际上是同一个片段占了两格，等于没做。

所以这里要**把对方的名字和对比词从句子里去掉**，把问题改写成针对
单一业务线的问法："证券在适当性义务上的法律规定"。
这不是美化措辞，而是**让两条子查询真的在问不同的事**。
"""

# 三个业务线。这是语料的组织方式本身（三条业务线各有一套规则），
# 不是我临时编的分类。
BUSINESS_LINES: dict[str, re.Pattern[str]] = {
    '证券': re.compile(r'证券'),
    '期货': re.compile(r'期货'),
    '基金': re.compile(r'基金'),
}

# 对比意图的标记词。只有同时命中"两个业务线 + 对比意图"才拆——
# 只提了"证券期货"（这是一个词，指整个行业）而没有对比意图的，
# 拆开反而把问题切碎了。
COMPARISON_MARKERS = (
    '区别', '差异', '不同', '对比', '相比', '分别', '异同', '一样吗', '有什么不一样',
    # 下面这些是补上来的，全是**真实问法**里会出现、而第一版漏掉的：
    # 漏掉它们的后果很直接——`is_comparison` 判成 False，**连门都进不了**，
    # 后面有再好的词条也没用。
    # 实测漏掉的是"销售人员管理上有什么**共同要求**"这一句。
    '共同要求', '共同点', '各自负责', '分别由谁', '分别负责',
    '有什么不同', '有何不同', '异同点', '是否一致',
    # 也是真实问法里漏掉的一个："证券和期货两条线**谁负责**制定产品风险等级名录"。
    # 它不是"对比"这个词，但它的意思就是"两边各自怎么分工"——
    # 漏掉它的后果同样是连门都进不了。
    '谁负责',
)

# "证券期货"在监管语境里是一个固定搭配，指**整个行业**，不是"证券 + 期货"两条线。
#
# 这个坑实际踩过：问"证券期货投资者适当性管理办法现在有效的是哪个版本"，
# 同时出现了"证券"和"期货"，被判成跨两条业务线的对比题，
# 于是被路由到"证券与期货适当性义务对照"的词条上——答非所问。
#
# 但不能简单地把"证券期货"整串删掉：**"证券期货基金三条线"是实打实的三条线**。
# 区别在于后面跟的是什么——
#   跟"投资者/市场/经营机构/业/监管"→ 是行业词，要去掉；
#   跟"基金/、/和"→ 是三条线并列举，要留下。
INDUSTRY_TERM_PATTERN = re.compile(r'证券期货(?=投资者|市场|经营机构|业|监管|交易场所|规章|法律|行业)')


def detect_lines(query: str) -> list[str]:
    """找出问题里提到了哪几条业务线。"""

    text = INDUSTRY_TERM_PATTERN.sub('', query or '')
    return [label for label, pattern in BUSINESS_LINES.items() if pattern.search(text)]


def split_query(query: str) -> list[str]:
    """需要拆分就返回子查询列表，不需要就返回空列表。

    子查询的构造是"去掉对方的名字和对比词，只留这一条业务线"，
    而不是"加个前缀"——理由见模块开头的说明。
    """

    text = query or ''
    if not any(marker in text for marker in COMPARISON_MARKERS):
        return []

    lines = detect_lines(text)
    if len(lines) < 2:
        return []

    sub_queries: list[str] = []
    for label in lines:
        restated = text
        # 去掉**其它**业务线的名字（连"…线"的写法一起去）。
        # 留下的那一个就是这条子查询的对象——**不再另加前缀**，
        # 否则会出现"证券 证券在…"这种重复。
        for other in lines:
            if other == label:
                continue
            restated = restated.replace(f'{other}线', '').replace(other, '')
        # 去掉对比词——"有什么区别"是原问题的意图，对单条业务线没有意义。
        for marker in COMPARISON_MARKERS:
            restated = restated.replace(marker, '')
        # 清掉被挖空之后剩下的连接词和标点，否则会留下"证券和在适当性义务上的…"。
        for filler in ('有什么', '什么', '和', '与', '、', '，', ',', '及', '吗', '？', '?'):
            restated = restated.replace(filler, '')
        restated = restated.strip()
        if restated:
            sub_queries.append(restated)

    # 两条子查询如果清完变成一样，说明它们问的还是同一件事，拆了没意义。
    if len(set(sub_queries)) < len(sub_queries):
        return []
    return sub_queries


__all__ = ['BUSINESS_LINES', 'COMPARISON_MARKERS', 'detect_lines', 'split_query']
